import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const port = 14318;
const url = `http://127.0.0.1:${port}`;

test('local server enforces origins and persists notebook changes', async t => {
  const dataDir = await mkdtemp(join(tmpdir(), 'lumen-test-'));
  const child = spawn(process.execPath, ['server.mjs'], { cwd: new URL('../', import.meta.url), env: { ...process.env, LUMEN_PORT: String(port), LUMEN_DATA_DIR: dataDir }, stdio: ['ignore', 'pipe', 'pipe'] });
  t.after(async () => { child.kill('SIGTERM'); await once(child, 'close'); await rm(dataDir, { recursive: true, force: true }); });
  await Promise.race([once(child.stdout, 'data'), once(child, 'error').then(([error]) => { throw error; }), new Promise((_, reject) => setTimeout(() => reject(new Error('Test server did not start')), 5000).unref())]);
  const response = await fetch(url);
  assert.equal(response.status, 200);
  assert.match(response.headers.get('content-security-policy'), /script-src 'self'/);
  assert.equal((await fetch(`${url}/api/studies`, { headers: { Origin: 'https://outside.example' } })).status, 403);
  assert.equal((await fetch(`${url}/api/demo`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: '{}' })).status, 403);
  const demo = await (await fetch(`${url}/api/demo`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: '{"mode":"study"}' })).json();
  assert.equal(demo.mode, 'study');
  const english = await (await fetch(`${url}/api/demo`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: '{"mode":"direct","language":"en"}' })).json();
  assert.equal(english.language, 'en');
  assert.match(english.introduction, /Two scenes/);
  const notes = '<script>This is only a note, never HTML.</script>';
  const saved = await fetch(`${url}/api/studies/${demo.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: JSON.stringify({ notes, interactiveState: { choice: 'B' }, hypothesisDraft: 'Uma hipótese aberta.' }) });
  assert.equal(saved.status, 200);
  const loaded = await (await fetch(`${url}/api/studies/${demo.id}`)).json();
  assert.equal(loaded.notes, notes);
  assert.equal(loaded.interactiveState.choice, 'B');
  assert.equal(loaded.hypothesisDraft, 'Uma hipótese aberta.');
  const thread = { church: { label: 'Catecismo', locator: 'CIC 1808' }, scene: { title: 'Um chamado na floresta', locator: 'Great Deku Tree' }, note: 'Coragem diante de um pedido.', createdAt: new Date().toISOString() };
  await fetch(`${url}/api/studies/${demo.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: JSON.stringify({ threads: [thread] }) });
  await fetch(`${url}/api/studies/${demo.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: JSON.stringify({ threads: [{ church: '<b>x</b>', scene: {} }] }) });
  const linked = await (await fetch(`${url}/api/studies/${demo.id}`)).json();
  assert.deepEqual(linked.threads, [thread]);
  const listed = (await (await fetch(`${url}/api/studies`)).json()).find(s => s.id === demo.id);
  assert.equal(listed.theme, demo.title);
  assert.equal(listed.depth, 'standard');
  const nonce = 'a'.repeat(32);
  const rendered = await (await fetch(`${url}/api/render`, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Lumen': 'local' }, body: JSON.stringify({ nonce, html: '<h2>Isolated presentation</h2>' }) })).json();
  const page = await fetch(`${url}/render/${rendered.id}`);
  assert.match(page.headers.get('content-security-policy'), /sandbox allow-scripts/);
  assert.match(page.headers.get('content-security-policy'), /connect-src 'none'/);
  assert.match(await page.text(), /Isolated presentation/);
  const picture = demo.images.find(image => image.status === 'ok');
  const media = await fetch(`${url}/media/${picture.file}`);
  assert.equal(media.status, 200);
  assert.match(media.headers.get('content-type'), /^image\//);
  assert.equal((await fetch(`${url}/media/../studies/${demo.id}.json`)).status, 404);
  assert.equal((await fetch(`${url}/media/not-an-image.svg`)).status, 404);
  assert.match(page.headers.get('content-security-policy'), /img-src data: http:\/\/127\.0\.0\.1:\d+\/media\//);
  assert.equal((await fetch(`${url}/.data/studies/${demo.id}.json`)).status, 403);
  assert.equal((await fetch(`${url}/api/studies/../../README.md`)).status, 404);
});
