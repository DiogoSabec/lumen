// Interface language. Portuguese text is the key; English lives here.
// Static page text is marked with data-i18n* attributes in index.html.
export const LANGS = ['pt', 'en'];
let lang = 'pt';
try { const saved = localStorage.getItem('lumen-lang'); if (LANGS.includes(saved)) lang = saved; } catch {}
export const getLang = () => lang;
export const locale = () => lang === 'en' ? 'en-US' : 'pt-BR';
export function setLang(next) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try { localStorage.setItem('lumen-lang', next); } catch {}
}
const fill = (text, params) => text.replace(/\{(\w+)\}/g, (all, key) => Object.hasOwn(params, key) ? String(params[key]) : all);
export const t = (text, params = {}) => fill(lang === 'en' ? EN[text] ?? text : text, params);

// Messages written by the server (progress, errors, logins, checks).
const SERVER = [
  [/^Conferindo fontes: (\d+) de (\d+)…$/, 'Checking sources: $1 of $2…'],
  [/^Buscando imagens: (\d+) de (\d+)…$/, 'Fetching images: $1 of $2…'],
  [/^A fonte retornou HTTP (\d+)\.$/, 'The source returned HTTP $1.'],
  [/^O campo (\w+) excede o tamanho permitido\.$/, 'The $1 field is longer than allowed.']
];
export function tServer(message) {
  const text = String(message ?? '');
  if (lang !== 'en') return text;
  if (EN[text]) return EN[text];
  for (const [pattern, english] of SERVER) if (pattern.test(text)) return text.replace(pattern, english);
  return text;
}

export function applyStatic(root = document) {
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.dataset.ptHtml ??= el.innerHTML;
    el.innerHTML = lang === 'en' ? STATIC_EN[el.dataset.i18n] ?? el.dataset.ptHtml : el.dataset.ptHtml;
  }
  for (const attr of ['placeholder', 'aria-label', 'title', 'href']) {
    const data = `i18n${attr.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('')}`;
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) {
      const original = `pt${attr.replace('-', '')}`;
      el.dataset[original] ??= el.getAttribute(attr) || '';
      el.setAttribute(attr, lang === 'en' ? STATIC_EN[el.dataset[data]] ?? el.dataset[original] : el.dataset[original]);
    }
  }
}

